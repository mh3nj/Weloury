package eventbus

import (
	"encoding/json"
	"time"
)

// Severity is the operator-facing severity of an Event.
type Severity string

const (
	SeverityInfo     Severity = "info"
	SeverityWarning  Severity = "warning"
	SeverityCritical Severity = "critical"
)

// Type identifies the kind of Event. The eventbus package itself stays
// agnostic of what any given Type means; domain packages (process,
// service, health, ...) define their own Type constants alongside their
// own code as those subsystems are built (Phase 2+). Only the handful of
// lifecycle events the application core itself emits are defined here.
type Type string

const (
	// TypeBackendStarted is published once, after every subsystem has
	// finished initializing and the IPC server is accepting connections.
	TypeBackendStarted Type = "system.backend_started"

	// TypeBackendStopping is published once, at the start of graceful
	// shutdown, before any subsystem has actually stopped.
	TypeBackendStopping Type = "system.backend_stopping"

	// TypeHeartbeat is a Phase 1 placeholder proving the bus works
	// end-to-end (backend -> IPC event stream -> frontend) before any
	// real monitoring subsystem exists. Later phases add real periodic
	// events (metric samples, health check results) at their own natural
	// cadences; this one is removed once at least one of those exists.
	TypeHeartbeat Type = "system.heartbeat"
)

// Event is the unit of information carried on the Bus.
type Event struct {
	// ID uniquely identifies this event. Auto-generated by Publish if
	// left empty.
	ID string `json:"id"`

	// Timestamp is when the event occurred. Auto-set to time.Now().UTC()
	// by Publish if left zero.
	Timestamp time.Time `json:"timestamp"`

	Type     Type     `json:"type"`
	Source   string   `json:"source"`
	Severity Severity `json:"severity"`

	// Payload is arbitrary, event-type-specific structured data.
	Payload json.RawMessage `json:"payload,omitempty"`
}
